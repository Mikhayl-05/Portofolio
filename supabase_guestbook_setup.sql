-- ============================================================
-- SQL SETUP UNTUK GUESTBOOK PORTOFOLIO MIKHAYL
-- Jalankan query ini di Dashboard Supabase -> SQL Editor -> New Query -> Run
-- ============================================================

-- 1. Buat tabel guestbook
create table if not exists public.guestbook (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text not null,
  emoji text not null default '✨',
  message text not null
);

-- 2. Aktifkan Row Level Security (RLS) agar aman
alter table public.guestbook enable row level security;

-- 3. Izinkan SEMUA PENGUNJUNG (publik/anonim) membaca pesan
create policy "Public can read guestbook"
  on public.guestbook
  for select
  to anon, authenticated
  using (true);

-- 4. Izinkan SEMUA PENGUNJUNG (publik/anonim) mengirim pesan baru
create policy "Public can insert guestbook"
  on public.guestbook
  for insert
  to anon, authenticated
  with check (
    length(trim(name)) > 0 and
    length(trim(name)) <= 40 and
    length(trim(message)) > 0 and
    length(trim(message)) <= 280
  );

-- Selesai! Tabel siap digunakan langsung oleh portofolio.

