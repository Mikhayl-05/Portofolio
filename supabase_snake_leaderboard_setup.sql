-- 1. Buat tabel snake_leaderboard jika belum ada
create table if not exists public.snake_leaderboard (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  player_name text not null,
  score integer not null
);

-- 2. Aktifkan Row Level Security (RLS)
alter table public.snake_leaderboard enable row level security;

-- 3. Policy: Siapapun (anon & authenticated) dapat melihat leaderboard
drop policy if exists "Public can read snake leaderboard" on public.snake_leaderboard;
create policy "Public can read snake leaderboard"
  on public.snake_leaderboard
  for select
  to anon, authenticated
  using (true);

-- 4. Policy: Siapapun dapat mengirim skor dengan validasi skor > 0 dan nama valid
drop policy if exists "Public can insert score" on public.snake_leaderboard;
create policy "Public can insert score"
  on public.snake_leaderboard
  for insert
  to anon, authenticated
  with check (
    score > 0 and
    length(trim(player_name)) > 0 and
    length(player_name) <= 30
  );

-- 5. Index untuk performa query top ranking
create index if not exists idx_snake_leaderboard_score on public.snake_leaderboard (score desc);

